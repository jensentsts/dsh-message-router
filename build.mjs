import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = new URL('./', import.meta.url)
const files = ['contract.mjs', 'monitor.mjs', 'monitor-rpc.mjs', 'client-entry.mjs']
let body = ''
for (const name of files) {
  const source = (await readFile(new URL(name, root), 'utf8')).replace(/^import .+\r?\n/gmu, '').replace(/^export /gmu, '')
  body += `\n// ${name}\n${source}`
}
const en = JSON.parse(await readFile(new URL('locale/en.json', root), 'utf8')); const zh = JSON.parse(await readFile(new URL('locale/zh.json', root), 'utf8'))
const output = `// Generated by build.mjs from this package only.\nwindow.__ModuleLoader__.load({ id: 'dsh-super-agent-io', factory(require) {\nconst React = require('react'); const {z} = require('zod');\nconst en=${JSON.stringify(en)};\nconst zh=${JSON.stringify(zh)};\n${body}\nreturn { inject, apply };\n} });\n`
if (process.argv.includes('--check')) { if (await readFile(new URL('client.js', root), 'utf8') !== output) throw new Error('client.js is stale') }
else await writeFile(new URL('client.js', root), output)
